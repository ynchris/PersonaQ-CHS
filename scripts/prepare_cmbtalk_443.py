def main():
    s='export_base/facility/cmbtalk.bf.json';d=read(ROOT/s)
    p=ROOT/'translation/batches/443_marie_outings.generated.json';assert not p.exists()
    cat={r['key']:r for r in read(ROOT/'translation/catalog.working.json')};rows=[]
    for i,lines in sorted(T.items()):
        assert len(lines)==len(d['texts'][i]['lines']),i
        for j,line in enumerate(lines):
            r=cat[f'{s}:{i}:{j}'];assert not r.get('translation');old=r['original']
            body=line+ ('\n' if TOKEN.sub('',old).endswith('\n') else '')
            full=LEADING.match(old).group()+body+TRAILING.search(old).group()
            assert TOKEN.findall(full)==TOKEN.findall(old),(i,j)
            a=TOKEN.sub('',old).splitlines();b=TOKEN.sub('',full).splitlines()
            assert len(b)<=len(a) and max(map(len,b))<=max(map(len,a)),(i,j)
            rows.append([i,j,d['texts'][i]['id'],body])
    write(p,dict(status='draft',sources={s:rows},source_hashes={s:hashlib.sha256((ROOT/s).read_bytes()).hexdigest()},review_notes=['玛丽外出、寻找记忆和社群日常13—65整段；沿用既有角色名和朱尼斯，旧作场所冲奈市/熟食大学暂按原文翻译。','重复段落复用本批一致措辞，未冒称Q2新增匹配；保留全部原始控制码和分支。旧作遗留文本，未验证PQ运行时可达性。']))
    print('Pages:',len(rows))
